package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/token"
	"go/types"
	"log"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"text/template"

	"golang.org/x/tools/go/packages"
)

const (
	generatedFileName = "reset.gen.go"
	generatedHeader   = "// Code generated by cmd/reset; DO NOT EDIT.\n"
	directive         = "generate:reset"
)

type generatedType struct {
	name      string
	typeSpec  *ast.TypeSpec
	structure *types.Struct
}

func main() {
	if err := run(); err != nil {
		log.New(os.Stderr, "", 0).Fatal(err)
	}
}

func run() error {
	workingDirectory, err := os.Getwd()
	if err != nil {
		return fmt.Errorf("get working directory: %w", err)
	}

	root, err := moduleRoot(workingDirectory)
	if err != nil {
		return err
	}

	return generate(root)
}

func moduleRoot(directory string) (string, error) {
	for {
		if _, err := os.Stat(filepath.Join(directory, "go.mod")); err == nil {
			return directory, nil
		} else if !os.IsNotExist(err) {
			return "", fmt.Errorf("inspect module file: %w", err)
		}

		parent := filepath.Dir(directory)
		if parent == directory {
			return "", fmt.Errorf("find module root: go.mod not found")
		}
		directory = parent
	}
}

func generate(root string) error {
	configuration := &packages.Config{
		Dir: root,
		Mode: packages.NeedName |
			packages.NeedFiles |
			packages.NeedCompiledGoFiles |
			packages.NeedSyntax |
			packages.NeedTypes |
			packages.NeedTypesInfo |
			packages.NeedModule,
	}

	loadedPackages, err := packages.Load(configuration, "./...")
	if err != nil {
		return fmt.Errorf("load Go packages: %w", err)
	}
	if packages.PrintErrors(loadedPackages) > 0 {
		return fmt.Errorf("load Go packages: package type errors found")
	}

	sort.Slice(loadedPackages, func(i, j int) bool {
		return loadedPackages[i].PkgPath < loadedPackages[j].PkgPath
	})

	for _, loadedPackage := range loadedPackages {
		if loadedPackage.Module == nil || loadedPackage.Module.Dir != root {
			continue
		}
		if err := generatePackage(loadedPackage); err != nil {
			return fmt.Errorf("generate package %s: %w", loadedPackage.PkgPath, err)
		}
	}

	return nil
}

func generatePackage(pkg *packages.Package) error {
	generatedTypes, err := findGeneratedTypes(pkg)
	if err != nil {
		return err
	}

	packageDirectory, err := packageDirectory(pkg)
	if err != nil {
		return err
	}
	outputPath := filepath.Join(packageDirectory, generatedFileName)
	if len(generatedTypes) == 0 {
		return removeStaleGeneratedFile(outputPath)
	}

	if err := rejectExistingResetMethods(pkg, generatedTypes); err != nil {
		return err
	}

	generatedSource, err := renderPackage(pkg, generatedTypes)
	if err != nil {
		return err
	}
	formattedSource, err := format.Source(generatedSource)
	if err != nil {
		return fmt.Errorf("format generated source: %w", err)
	}

	currentSource, err := os.ReadFile(outputPath)
	if err == nil && bytes.Equal(currentSource, formattedSource) {
		return nil
	}
	if err != nil && !os.IsNotExist(err) {
		return fmt.Errorf("read generated file: %w", err)
	}
	if err := os.WriteFile(outputPath, formattedSource, 0o644); err != nil {
		return fmt.Errorf("write generated file: %w", err)
	}

	return nil
}

func findGeneratedTypes(pkg *packages.Package) ([]generatedType, error) {
	typesByName := make(map[string]generatedType)

	for _, file := range pkg.Syntax {
		if filepath.Base(pkg.Fset.Position(file.Pos()).Filename) == generatedFileName {
			continue
		}

		for _, declaration := range file.Decls {
			typeDeclaration, ok := declaration.(*ast.GenDecl)
			if !ok || typeDeclaration.Tok != token.TYPE {
				continue
			}

			for _, spec := range typeDeclaration.Specs {
				typeSpec, ok := spec.(*ast.TypeSpec)
				if !ok || typeSpec.Assign.IsValid() {
					continue
				}
				if _, ok := typeSpec.Type.(*ast.StructType); !ok {
					continue
				}
				if !hasDirective(typeSpec.Doc) && !hasDirective(typeDeclaration.Doc) {
					continue
				}

				definition := pkg.TypesInfo.Defs[typeSpec.Name]
				if definition == nil {
					return nil, fmt.Errorf("resolve marked type %s", typeSpec.Name.Name)
				}
				namedType, ok := types.Unalias(definition.Type()).(*types.Named)
				if !ok {
					return nil, fmt.Errorf("resolve named type %s", typeSpec.Name.Name)
				}
				structure, ok := namedType.Underlying().(*types.Struct)
				if !ok {
					return nil, fmt.Errorf("resolve struct type %s", typeSpec.Name.Name)
				}

				typesByName[typeSpec.Name.Name] = generatedType{
					name:      typeSpec.Name.Name,
					typeSpec:  typeSpec,
					structure: structure,
				}
			}
		}
	}

	generatedTypes := make([]generatedType, 0, len(typesByName))
	for _, generatedType := range typesByName {
		generatedTypes = append(generatedTypes, generatedType)
	}
	sort.Slice(generatedTypes, func(i, j int) bool {
		return generatedTypes[i].name < generatedTypes[j].name
	})

	return generatedTypes, nil
}

func hasDirective(comments *ast.CommentGroup) bool {
	if comments == nil {
		return false
	}
	for _, comment := range comments.List {
		commentText := strings.TrimSpace(strings.TrimPrefix(comment.Text, "//"))
		if commentText == directive {
			return true
		}
	}
	return false
}

func packageDirectory(pkg *packages.Package) (string, error) {
	if len(pkg.CompiledGoFiles) == 0 {
		return "", fmt.Errorf("package has no compiled Go files")
	}
	return filepath.Dir(pkg.CompiledGoFiles[0]), nil
}

func rejectExistingResetMethods(pkg *packages.Package, generatedTypes []generatedType) error {
	markedTypes := make(map[string]struct{}, len(generatedTypes))
	for _, generatedType := range generatedTypes {
		markedTypes[generatedType.name] = struct{}{}
	}

	for _, file := range pkg.Syntax {
		if filepath.Base(pkg.Fset.Position(file.Pos()).Filename) == generatedFileName {
			continue
		}
		for _, declaration := range file.Decls {
			function, ok := declaration.(*ast.FuncDecl)
			if !ok || function.Recv == nil || function.Name.Name != "Reset" {
				continue
			}

			receiverName := receiverTypeName(function.Recv.List[0].Type)
			if _, exists := markedTypes[receiverName]; exists {
				return fmt.Errorf("type %s already declares Reset()", receiverName)
			}
		}
	}
	return nil
}

func receiverTypeName(expression ast.Expr) string {
	switch receiver := expression.(type) {
	case *ast.StarExpr:
		return receiverTypeName(receiver.X)
	case *ast.Ident:
		return receiver.Name
	case *ast.IndexExpr:
		return receiverTypeName(receiver.X)
	case *ast.IndexListExpr:
		return receiverTypeName(receiver.X)
	default:
		return ""
	}
}

func renderPackage(pkg *packages.Package, generatedTypes []generatedType) ([]byte, error) {
	data := packageTemplateData{
		Header:         generatedHeader,
		PackageName:    pkg.Name,
		Types:          make([]resetTemplateData, 0, len(generatedTypes)),
		ZeroHelperName: packageHelperName(pkg),
	}
	for _, generatedType := range generatedTypes {
		receiverType := generatedType.name
		if generatedType.typeSpec.TypeParams != nil && len(generatedType.typeSpec.TypeParams.List) > 0 {
			receiverType += "[" + typeParameterNames(generatedType.typeSpec.TypeParams) + "]"
		}
		resetData := resetTemplateData{
			Name:         generatedType.name,
			ReceiverType: receiverType,
			Statements:   make([]string, 0, generatedType.structure.NumFields()),
		}
		for fieldIndex := 0; fieldIndex < generatedType.structure.NumFields(); fieldIndex++ {
			field := generatedType.structure.Field(fieldIndex)
			statements := resetStatements("r."+field.Name(), field.Type(), data.ZeroHelperName, 1)
			resetData.Statements = append(resetData.Statements, statements...)
		}
		data.Types = append(data.Types, resetData)
	}

	resetTemplate, err := template.New("reset").Parse(resetSourceTemplate)
	if err != nil {
		return nil, fmt.Errorf("parse reset template: %w", err)
	}
	var source bytes.Buffer
	if err := resetTemplate.Execute(&source, data); err != nil {
		return nil, fmt.Errorf("execute reset template: %w", err)
	}
	return source.Bytes(), nil
}

func resetStatements(expression string, fieldType types.Type, zeroHelperName string, indentation int) []string {
	indent := strings.Repeat("\t", indentation)
	unaliasType := types.Unalias(fieldType)
	if _, isTypeParameter := unaliasType.(*types.TypeParam); isTypeParameter {
		return []string{indent + expression + " = " + zeroHelperName + "(" + expression + ")"}
	}
	underlying := unaliasType.Underlying()

	switch typedType := underlying.(type) {
	case *types.Pointer:
		innerExpression := "*(" + expression + ")"
		innerStatements := resetStatements(innerExpression, typedType.Elem(), zeroHelperName, indentation+1)
		statements := []string{indent + "if " + expression + " != nil {"}
		statements = append(statements, innerStatements...)
		statements = append(statements, indent+"}")
		return statements
	case *types.Slice:
		return []string{indent + expression + " = (" + expression + ")[:0]"}
	case *types.Map:
		return []string{indent + "clear(" + expression + ")"}
	case *types.Struct:
		if hasResetMethod(fieldType) {
			return []string{indent + "(" + expression + ").Reset()"}
		}
		return []string{indent + expression + " = " + zeroHelperName + "(" + expression + ")"}
	case *types.Interface:
		return []string{
			indent + "if " + expression + " != nil {",
			indent + "\tif resetter, ok := any(" + expression + ").(interface{ Reset() }); ok {",
			indent + "\t\tresetter.Reset()",
			indent + "\t} else {",
			indent + "\t\t" + expression + " = " + zeroHelperName + "(" + expression + ")",
			indent + "\t}",
			indent + "}",
		}
	default:
		return []string{indent + expression + " = " + zeroHelperName + "(" + expression + ")"}
	}
}

func hasResetMethod(fieldType types.Type) bool {
	methodSet := types.NewMethodSet(types.NewPointer(fieldType))
	for index := 0; index < methodSet.Len(); index++ {
		method := methodSet.At(index).Obj()
		if method.Name() != "Reset" {
			continue
		}
		signature, ok := method.Type().(*types.Signature)
		if ok && signature.Params().Len() == 0 && signature.Results().Len() == 0 {
			return true
		}
	}
	return false
}

func typeParameterNames(parameters *ast.FieldList) string {
	names := make([]string, 0, parameters.NumFields())
	for _, parameter := range parameters.List {
		for _, name := range parameter.Names {
			names = append(names, name.Name)
		}
	}
	return strings.Join(names, ", ")
}

func packageHelperName(pkg *packages.Package) string {
	existingNames := make(map[string]struct{})
	for _, file := range pkg.Syntax {
		if filepath.Base(pkg.Fset.Position(file.Pos()).Filename) == generatedFileName {
			continue
		}
		for _, declaration := range file.Decls {
			switch typedDeclaration := declaration.(type) {
			case *ast.FuncDecl:
				if typedDeclaration.Recv == nil {
					existingNames[typedDeclaration.Name.Name] = struct{}{}
				}
			case *ast.GenDecl:
				for _, spec := range typedDeclaration.Specs {
					switch typedSpec := spec.(type) {
					case *ast.TypeSpec:
						existingNames[typedSpec.Name.Name] = struct{}{}
					case *ast.ValueSpec:
						for _, name := range typedSpec.Names {
							existingNames[name.Name] = struct{}{}
						}
					}
				}
			}
		}
	}

	name := "resetZeroValue"
	for suffix := 1; ; suffix++ {
		if _, exists := existingNames[name]; !exists {
			return name
		}
		name = fmt.Sprintf("resetZeroValue%d", suffix)
	}
}

func removeStaleGeneratedFile(path string) error {
	generatedSource, err := os.ReadFile(path)
	if os.IsNotExist(err) {
		return nil
	}
	if err != nil {
		return fmt.Errorf("read generated file: %w", err)
	}
	if !bytes.HasPrefix(generatedSource, []byte(generatedHeader)) {
		return nil
	}
	if err := os.Remove(path); err != nil {
		return fmt.Errorf("remove stale generated file: %w", err)
	}
	return nil
}
